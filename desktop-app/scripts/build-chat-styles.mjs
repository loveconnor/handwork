import { readFile, writeFile } from 'node:fs/promises';
import postcss from 'postcss';

// Keep the embedded renderer's styles in sync without changing the native shell.
const scope = ':where(.generated-chat-ui, [data-base-ui-portal])';
const root = new URL('../', import.meta.url);
const { version } = JSON.parse(await readFile(new URL('node_modules/honestui/package.json', root), 'utf8'));
const license = await readFile(new URL('components/ui/LICENSE', root), 'utf8');
const header = `/*! Generated by scripts/build-chat-styles.mjs from honestui ${version}.\n\n${license}\n*/\n`;
const output = [];
for (const file of ['theme.css', 'ai.css', 'charts.css', 'prose.css', 'syntax.css']) {
  const css = postcss.parse(await readFile(new URL(`node_modules/honestui/dist/${file}`, root), 'utf8'));
  css.walkRules(rule => {
    for (let parent = rule.parent; parent; parent = parent.parent) {
      if (parent.type === 'atrule' && /keyframes$/.test(parent.name)) return;
    }
    rule.selectors = rule.selectors.flatMap(selector => {
      if (/^:(root|host)$/.test(selector) || selector === '[data-style]') return scope;
      if (file === 'theme.css' && selector.startsWith('[data-')) {
        const scoped = `:where(.generated-chat-ui):is(${selector})`;
        if (selector === '[data-theme="light"]') return [scoped, 'html.theme-light [data-base-ui-portal]'];
        if (selector === '[data-theme="dark"]') return [scoped, 'html:not(.theme-light) [data-base-ui-portal]'];
        return scoped;
      }
      return `${scope} ${selector}`;
    });
  });
  output.push(css.toString());
}
await writeFile(new URL('src/styles/honest-generated.css', root),
  header + output.join('\n'));
await writeFile(new URL('src/styles/honest-prose.css', root),
  header +
  await readFile(new URL('node_modules/honestui/dist/prose.css', root), 'utf8'));
