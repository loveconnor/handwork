import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
const version = '0.16.0';
const system = process.platform === 'darwin' ? 'macos' : 'windows';
const architecture = process.arch === 'arm64' ? 'aarch64' : 'x86_64';
const indexResponse = await fetch('https://ziglang.org/download/index.json');
if (!indexResponse.ok) throw new Error('Could not fetch Zig release metadata');
const release = (await indexResponse.json())[version]?.[`${architecture}-${system}`];
if (!release) throw new Error(`Zig ${version} is unavailable for ${architecture}-${system}`);
const response = await fetch(release.tarball);
if (!response.ok) throw new Error('Could not download Zig');
const bytes = Buffer.from(await response.arrayBuffer());
if (createHash('sha256').update(bytes).digest('hex') !== release.shasum) throw new Error('Zig checksum mismatch');
const directory = path.join(process.env.RUNNER_TEMP, 'desktop-zig');
await mkdir(directory, { recursive: true });
const archive = path.join(directory, path.basename(new URL(release.tarball).pathname));
await writeFile(archive, bytes);
execFileSync('tar', ['-xf', archive, '-C', directory], { stdio: 'inherit' });
const extracted = path.join(directory, path.basename(archive).replace(/\.(zip|tar\.xz)$/, ''));
await writeFile(process.env.GITHUB_PATH, `${extracted}\n`, { flag: 'a' });
